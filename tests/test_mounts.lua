local ns, T = NS, T
local Core, Mounts = ns.Core, ns.Mounts
local riding
local function reset()
  riding = nil
  _G.IsMounted = function() return riding ~= nil end
  _G.C_MountJournal = {
    GetMountIDs = function() return {101,202} end,
    GetMountInfoByID = function(id) return "Monture " .. id, id + 1000, 1, riding == id end,
  }
  Core.ResetToDefaults()
end
local function mount(id) riding = id; Mounts.Sync() end
local function roundtrip(s)
  return ns.Comm:DeserializeState("STATE_DATA", ns.Comm.SerializeState(s), "Other-Realm")
end
T.describe("Mount rules and persistence", function()
  T.it("disables rider dodge automatically for both damage types and restores it on dismount", function()
    reset(); Core.SetDodge(30); Core.SetHP(100,100); Core.SetArmor(5,0)
    mount(101)
    T.assertTrue(Core.state.mounted); T.assertEq(GrosOrteilAPI.GetDodge(),0)
    Core.DamageWithArmor(20); T.assertEq(Core.state.hp,85)
    Core.DamageTrue(10); T.assertEq(Core.state.hp,75)
    T.assertFalse(Core.GetHistory()[1].dodged)
    T.assertEq(Core.state.dodge,30)
    mount(nil); Core.DamageWithArmor(20)
    T.assertEq(Core.state.hp,75); T.assertTrue(Core.GetHistory()[1].dodged)
    T.assertEq(GrosOrteilAPI.GetDodge(),30)
  end)
  T.it("preserves mount HP and defense separately for every summoned mount", function()
    reset(); mount(101)
    Mounts.SetField("hp",10); Mounts.SetField("armor",3); Mounts.SetField("dodge",5)
    mount(202); T.assertEq(Mounts.GetSelected().hp,20)
    Mounts.SetField("maxHp",80); Mounts.SetField("hp",70)
    mount(101); T.assertEq(Mounts.GetSelected().hp,10)
    T.assertEq(Mounts.GetSelected().armor,3)
    ns.Core_Init(); Mounts.Sync()
    T.assertEq(Mounts.GetSelected().hp,10)
    mount(202); T.assertEq(Mounts.GetSelected().hp,70)
    mount(nil)
  end)
  T.it("uses mount dodge and armor without applying rider class defenses", function()
    reset(); mount(101); Mounts.SetField("maxHp",100); Mounts.SetField("hp",100)
    Mounts.SetField("armor",5); Mounts.SetField("dodge",10)
    Core.SetShamanPosture("FEU")
    Core.MountAction("DAMAGE_ARMOR",10); T.assertEq(Mounts.GetSelected().hp,100)
    Core.MountAction("DAMAGE_ARMOR",25); T.assertEq(Mounts.GetSelected().hp,80)
    Core.MountAction("DAMAGE_TRUE",15); T.assertEq(Mounts.GetSelected().hp,65)
    Core.MountAction("DAMAGE_DIRECT",5); T.assertEq(Mounts.GetSelected().hp,60)
    T.assertEq(Core.GetHistory()[1].subject,"MOUNT")
    T.assertEq(Core.state.hp,50)
    Core.MountAction("DAMAGE_DIRECT",50); Core.MountAction("HEAL",80)
    T.assertEq(Mounts.GetSelected().hp,25)
    Core.MountAction("RESTORE"); T.assertEq(Mounts.GetSelected().hp,100)
    mount(nil)
  end)
  T.it("shares the pet object in both directions and preserves independent stats when unlinked", function()
    reset(); Core.SetPetEnabled(true); Core.SetPetHP(60,80); Core.SetPetArmor(4,0)
    mount(101); Mounts.SetField("hp",17); Mounts.SetPetLink(true)
    T.assertEq(Mounts.GetSelected(),Core.GetPet())
    Core.MountAction("DAMAGE_ARMOR",14); T.assertEq(Core.state.pet.hp,50)
    Core.PetHeal(5); T.assertEq(Mounts.GetSelected().hp,55)
    Mounts.SetField("dodge",9); T.assertEq(Core.state.pet.dodge,9)
    local wire = roundtrip(Core.state)
    T.assertEq(wire.mount.hp,55); T.assertTrue(wire.mount.isPet)
    Mounts.SetPetLink(false); T.assertEq(Mounts.GetSelected().hp,17)
    T.assertEq(Core.state.pet.hp,55); mount(nil)
  end)
  T.it("undo restores stats and pet links without replaying real mounting state", function()
    reset(); mount(101); Core.BreakUndoCoalesce(); Mounts.SetField("armor",8)
    mount(nil); Core.Undo(); T.assertEq(Mounts.GetSelected().armor,0)
    T.assertFalse(Core.state.mounted)
    Core.Redo(); T.assertEq(Mounts.GetSelected().armor,8)
    Core.BreakUndoCoalesce(); Mounts.SetPetLink(true)
    Core.Undo(); T.assertFalse(select(2,Mounts.GetSelected()).isPet)
    Core.Redo(); T.assertTrue(select(2,Mounts.GetSelected()).isPet)
    Core.BreakUndoCoalesce(); Core.MountAction("DAMAGE_DIRECT",5)
    Core.Undo(); T.assertEq(Core.state.pet.hp,20)
  end)
  T.it("keeps a newly discovered active mount when undoing an earlier sheet edit", function()
    reset(); mount(101); Core.BreakUndoCoalesce(); Mounts.SetField("armor",8)
    mount(202); Core.Undo()
    T.assertEq(Core.state.mounts[101].armor,0)
    T.assertEq(Mounts.GetActive().hp,20)
    T.assertEq(roundtrip(Core.state).mount.name,"Monture 202")
    mount(nil)
  end)
  T.it("handles unavailable journal data and publishes only the active sheet", function()
    reset(); mount(101); Mounts.SetField("name","Selle")
    mount(202); local wire = roundtrip(Core.state)
    T.assertTrue(wire.mounted); T.assertEq(wire.mount.name,"Monture 202")
    T.assertNil(wire.mounts)
    mount(nil); wire = roundtrip(Core.state)
    T.assertFalse(wire.mounted); T.assertNil(wire.mount)
    _G.C_MountJournal = nil; mount(999)
    T.assertTrue(Core.state.mounted); T.assertEq(Core.state.activeMountID,0)
    Core.SetDodge(10); Core.DamageTrue(5); T.assertEq(Core.state.hp,45)
    mount(nil)
    T.assertFalse(roundtrip({hp=30,maxHp=50}).mounted)
  end)
  T.it("rejects invalid fields and IDs without corrupting the selected sheet", function()
    reset(); mount(101)
    for _,value in ipairs({0/0,math.huge,"bad"}) do
      T.assertFalse(Mounts.SetField("hp",value)); T.assertFalse(Mounts.Select(value))
    end
    T.assertFalse(Mounts.Select(nil)); T.assertFalse(Mounts.SetField("mounted",true))
    T.assertEq(Mounts.GetSelected().hp,20); mount(nil)
  end)
end)
T.describe("Cambuse regeneration and migration",function()
  T.it("applies +2 regeneration independently and supports heal caps and undo",function()
    reset(); Core.SetHP(30,50); Core.SetPetEnabled(true); Core.SetPetHP(10,20)
    Core.BreakUndoCoalesce(); Core.ToggleAffix("CAMBUSE_REGEN")
    T.assertEq(Core.state.regenParTour,3)
    Core.Undo(); T.assertEq(Core.state.regenParTour,1)
    Core.Redo(); Core.RegenParTour(); T.assertEq(Core.state.hp,33)
    Core.TogglePetAffix("CAMBUSE_REGEN"); Core.PetRegenParTour()
    T.assertEq(Core.state.pet.hp,12); T.assertEq(Core.state.pet.regenParTour,2)
    Core.NextTurn(); T.assertTrue(Core.state.affixes.CAMBUSE_REGEN)
    Core.ToggleAffix("CAMBUSE_REGEN"); T.assertEq(Core.state.regenParTour,1)
    Core.TogglePetAffix("CAMBUSE_REGEN"); T.assertEq(Core.state.pet.regenParTour,0)
  end)
  T.it("upgrades old active bonuses once on both sheets and removes the upgraded amounts",function()
    reset()
    for _,t in ipairs({Core.state,Core.state.pet}) do
      t._cambuseV2=nil; t.hp=50; t.maxHp=70; t.dodge=8
      t.attaqueMelee=11; t.attaqueDistance=12
      t.affixes={CAMBUSE_PV=true,CAMBUSE_ATTAQUE=true}
      t.affixApplied={CAMBUSE_PV={hp=20,maxHp=20},CAMBUSE_ATTAQUE={attaqueMelee=10,attaqueDistance=10,dodge=5}}
    end
    ns.Core_Init(); ns.Core_Init()
    for _,t in ipairs({Core.state,Core.state.pet}) do
      T.assertEq(t.hp,55); T.assertEq(t.maxHp,75); T.assertEq(t.dodge,13)
      T.assertEq(t.affixApplied.CAMBUSE_PV.hp,25)
      T.assertEq(t.attaqueMelee,11)
    end
    Core.SetPetEnabled(true)
    Core.ToggleAffix("CAMBUSE_PV"); Core.TogglePetAffix("CAMBUSE_PV")
    Core.ToggleAffix("CAMBUSE_ATTAQUE"); Core.TogglePetAffix("CAMBUSE_ATTAQUE")
    for _,t in ipairs({Core.state,Core.state.pet}) do
      T.assertEq(t.hp,30); T.assertEq(t.maxHp,50); T.assertEq(t.dodge,3)
    end
  end)
end)
