return function(ns, frames, mocks, T)
  local Core, UI, Affixes = ns.Core, ns.UI, ns.Affixes
  local function click(button) button:RunScript("OnClick") end
  local function reset(pet)
    -- Close outstanding drafts before replacing the sheet.
    click(UI.customAffixes.cancel); click(UI.petCustomAffixes.cancel)
    Core.ResetToDefaults(); Core.SetPetEnabled(true)
    UI.setSidebarSection(pet and 2 or 1)
    UI.setTab(pet and UI.TAB_IDS.PET_AFFIXES or UI.TAB_IDS.PLAYER_AFFIXES)
    return pet and UI.petCustomAffixes or UI.customAffixes
  end
  local function choices(ui, rowIndex)
    local previous, items = _G.MenuUtil, {}
    _G.MenuUtil = { CreateContextMenu = function(owner, build)
      build(owner, {CreateButton=function(_,label,callback) items[label]=callback end})
    end }
    click(ui.rows[rowIndex].stat); _G.MenuUtil = previous
    return items
  end
  local function selectStat(ui, row, key)
    local items=choices(ui,row)
    T.assertNotNil(items[Affixes.BY_STAT[key].label])
    items[Affixes.BY_STAT[key].label]()
  end
  local function populate(ui, timed)
    click(ui.newButton); ui.name:SetText("Cri de guerre")
    selectStat(ui,1,"attaqueMelee"); ui.rows[1].value:SetText("+12")
    click(ui.addEffect); selectStat(ui,2,"dodge"); ui.rows[2].value:SetText("-2,5")
    if timed then click(ui.timed); ui.duration:SetText("2") end
  end
  local function create(ui,timed)
    populate(ui,timed); click(ui.save)
    T.assertFalse(ui.editor:IsShown(),ui.error:GetText())
    return ui.cards[1]
  end
  local function chooseColor(ui,r,g,b)
    click(ui.color)
    local info=ColorPickerFrame:GetExtraInfo()
    ColorPickerFrame.Content.ColorPicker:SetColorRGB(r,g,b)
    info.swatchFunc()
    return info
  end
  T.describe("Custom affix controls",function()
    T.it("creates multiple signed stat rows with optional duration and native color selection",function()
      local ui=reset(); populate(ui,true)
      chooseColor(ui,.9,.3,.1); ColorPickerFrame:Hide(); click(ui.save)
      T.assertFalse(ui.editor:IsShown(),ui.error:GetText())
      local def=Core.state.customAffixes[1]
      T.assertEq(#def.effects,2); T.assertEq(def.effects[1].stat,"attaqueMelee")
      T.assertEq(def.effects[1].value,12); T.assertEq(def.effects[2].value,-2.5)
      T.assertEq(def.duration,2); T.assertNear(def.color.r,.9)
      T.assertEq(#UI.affixButtons,5); T.assertEq(Core.state.attaqueMelee,0)
      click(ui.cards[1].toggle); T.assertEq(Core.state.attaqueMelee,12)
      T.assertNear(ui.cards[1].toggle._borderColor[1],.9)
      T.assertTrue(UI.affixNextTurnButton:IsEnabled())
      click(UI.affixNextTurnButton); T.assertTrue(ui.cards[1].toggle:GetText():find("1 tours",1,true))
      Core.BreakUndoCoalesce(); click(UI.affixNextTurnButton)
      T.assertEq(Core.state.attaqueMelee,0); T.assertFalse(UI.affixNextTurnButton:IsEnabled())
      Core.Undo(); T.assertEq(Core.state.affixTurns[def.id],1)
      T.assertEq(Core.state.attaqueMelee,12)
    end)
    T.it("preserves invalid drafts and focused text during unrelated updates and fixes errors in place",function()
      local ui=reset(); populate(ui,true)
      ui.name:SetFocus(); ui.name:SetText("Brouillon conservé")
      ui.rows[1].value:SetText("abc"); Core.SetHP(42,50)
      T.assertEq(ui.rows[1].value:GetText(),"abc"); T.assertEq(ui.name:GetText(),"Brouillon conservé")
      click(ui.save); T.assertTrue(ui.editor:IsShown())
      T.assertEq(#Core.state.customAffixes,0); T.assertNeq(ui.error:GetText(),"")
      ui.rows[1].value:SetText("12"); selectStat(ui,2,"attaqueMelee")
      click(ui.save); T.assertEq(#Core.state.customAffixes,0)
      selectStat(ui,2,"dodge"); ui.duration:SetText("0")
      click(ui.save); T.assertEq(#Core.state.customAffixes,0)
      ui.duration:SetText("4"); click(ui.save)
      T.assertEq(Core.state.customAffixes[1].name,"Brouillon conservé")
      T.assertEq(Core.state.customAffixes[1].duration,4)
    end)
    T.it("keeps the original saved definition when editing is cancelled",function()
      local ui=reset(); local card=create(ui)
      click(card.edit); ui.name:SetText("Autre nom"); ui.rows[1].value:SetText("50")
      chooseColor(ui,.1,.8,.2); click(ui.cancel)
      T.assertFalse(ColorPickerFrame:IsShown())
      T.assertEq(Core.state.customAffixes[1].name,"Cri de guerre")
      T.assertEq(Core.state.customAffixes[1].effects[1].value,12)
      T.assertNear(Core.state.customAffixes[1].color.r,.5)
    end)
    T.it("can remove a stat row and save an unlimited affix without a stale duration",function()
      local ui=reset(); populate(ui,true)
      ui.rows[1].value:SetText("7"); click(ui.rows[2].remove)
      T.assertFalse(ui.rows[2]:IsShown()); T.assertEq(ui.rows[1].value:GetText(),"7")
      T.assertFalse(ui.rows[1].remove:IsEnabled())
      ui.duration:SetText("0"); click(ui.timed); click(ui.save)
      T.assertEq(#Core.state.customAffixes[1].effects,1)
      T.assertNil(Core.state.customAffixes[1].duration)
      click(ui.cards[1].toggle); T.assertFalse(UI.affixNextTurnButton:IsEnabled())
    end)
    T.it("keeps the pet catalogue independent and blocks activation while the pet is disabled",function()
      local ui=reset(true); local card=create(ui,true)
      T.assertEq(#Core.state.customAffixes,0); T.assertEq(#Core.state.pet.customAffixes,1)
      Core.SetPetEnabled(false); T.assertFalse(card.toggle:IsEnabled())
      click(card.toggle); T.assertEq(Core.state.pet.attaqueMelee,0)
      Core.SetPetEnabled(true); click(card.toggle); T.assertEq(Core.state.pet.attaqueMelee,12)
      click(UI.petAffixNextTurnButton); click(UI.petAffixNextTurnButton)
      T.assertEq(Core.state.pet.attaqueMelee,0)
      click(card.edit); T.assertNil(choices(ui,1)[Affixes.BY_STAT.perception.label])
      click(ui.cancel); UI.setSidebarSection(1)
    end)
    T.it("edits presentation while active, requires deactivation for effects and undoes deletion",function()
      local ui=reset(); local card=create(ui,true); click(card.toggle)
      click(UI.affixNextTurnButton); click(card.edit)
      ui.name:SetText("Cri renforcé"); chooseColor(ui,.2,.4,.6); ColorPickerFrame:Hide(); click(ui.save)
      local key=Core.state.customAffixes[1].id
      T.assertEq(Core.state.affixTurns[key],1); T.assertEq(Core.state.attaqueMelee,12)
      click(card.edit); ui.rows[1].value:SetText("30"); click(ui.save)
      T.assertTrue(ui.editor:IsShown()); T.assertEq(Core.state.attaqueMelee,12)
      click(card.toggle); click(ui.save); click(card.toggle)
      T.assertEq(Core.state.attaqueMelee,30)
      Core.BreakUndoCoalesce(); click(card.delete)
      T.assertEq(Core.state.attaqueMelee,0); T.assertFalse(card:IsShown())
      Core.Undo(); T.assertEq(Core.state.attaqueMelee,30); T.assertTrue(card:IsShown())
      T.assertTrue(card.toggle:GetText():find("Cri renforcé",1,true))
    end)
    T.it("cancels the color preview and ignores stale callbacks after tab or editor changes",function()
      local ui=reset(); populate(ui)
      local info=chooseColor(ui,.9,.1,.2)
      info.cancelFunc(); ColorPickerFrame:Hide(); click(ui.save)
      T.assertNear(Core.state.customAffixes[1].color.r,.5)
      click(ui.cards[1].edit); info=chooseColor(ui,.1,.9,.2)
      UI.setTab(UI.TAB_IDS.PLAYER_MAIN); T.assertFalse(ColorPickerFrame:IsShown())
      ColorPickerFrame.Content.ColorPicker:SetColorRGB(.7,.7,.7); info.swatchFunc()
      UI.setTab(UI.TAB_IDS.PLAYER_AFFIXES); click(ui.save)
      T.assertNear(Core.state.customAffixes[1].color.r,.5)
      click(ui.cards[1].edit); info=chooseColor(ui,.1,.9,.2)
      local foreign={r=0,g=0,b=0}; foreign.extraInfo=foreign
      ColorPickerFrame:SetupColorPickerAndShow(foreign)
      click(ui.cancel); T.assertTrue(ColorPickerFrame:IsShown())
      T.assertEq(ColorPickerFrame:GetExtraInfo(),foreign); info.swatchFunc()
      ColorPickerFrame:Hide()
    end)
    T.it("lays out all rows and cards below built-ins, grows the scroll area and reuses frames",function()
      local ui=reset(); populate(ui)
      for _=3,#Affixes.STATS do click(ui.addEffect) end
      T.assertFalse(ui.addEffect:IsEnabled())
      for i,stat in ipairs(Affixes.STATS) do selectStat(ui,i,stat.key) end
      frames.layout()
      local last=ui.rows[#Affixes.STATS]
      T.assertTrue(last:GetBottom()>ui.addEffect:GetTop())
      T.assertTrue(ui.save:GetBottom()>ui.editor:GetBottom())
      T.assertTrue(UI.affixNextTurnButton:GetBottom()>ui.newButton:GetTop())
      click(ui.save); T.assertFalse(ui.editor:IsShown(),ui.error:GetText())
      populate(ui); ui.name:SetText("Deuxième affixe"); click(ui.save)
      frames.layout()
      T.assertEq(ui.cards[1]:GetTop(),ui.cards[2]:GetTop())
      T.assertTrue(ui.cards[1]:GetRight()<ui.cards[2]:GetLeft())
      T.assertTrue(ui.cards[1].toggle:GetBottom()>ui.cards[1].edit:GetTop())
      local root=ui.newButton:GetParent()
      T.assertNear(ui.newButton:GetLeft()+ui.newButton:GetWidth()/2,root:GetLeft()+root:GetWidth()/2)
      populate(ui); ui.name:SetText("Third affix"); click(ui.save)
      frames.layout()
      T.assertTrue(ui.cards[1]:GetBottom()>ui.cards[3]:GetTop())
      T.assertEq(ui.cards[1]:GetLeft(),ui.cards[3]:GetLeft())
      local thirdKey=ui.cards[3].key
      click(ui.cards[2].delete); frames.layout()
      T.assertEq(ui.cards[2].key,thirdKey)
      T.assertEq(ui.cards[1]:GetTop(),ui.cards[2]:GetTop())
      T.assertFalse(ui.cards[3]:IsShown())
      local count=#frames.frames
      for _=1,5 do Core.SetHP(40,50); Core.SetHP(45,50) end
      T.assertEq(#frames.frames,count)
      T.assertEq(#mocks.errorHandlerCalls,0)
    end)
    T.it("ignores a stale stat menu after its row is removed or its editor is replaced",function()
      local ui=reset(); populate(ui)
      local menu=choices(ui,2); click(ui.rows[2].remove)
      menu[Affixes.BY_STAT.armor.label]()
      menu=choices(ui,1); click(ui.newButton)
      menu[Affixes.BY_STAT.armor.label]()
      T.assertTrue(ui.rows[1].stat:GetText():find("PV maximum",1,true))
      click(ui.cancel)
    end)
  end)
end
